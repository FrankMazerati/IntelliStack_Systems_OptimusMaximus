create extension if not exists pgcrypto;

create type public.membership_status as enum ('invited','active','suspended');
create type public.ticket_status as enum ('new','open','in_progress','waiting','resolved','closed');
create type public.ticket_priority as enum ('low','medium','high','critical');
create type public.approval_status as enum ('pending','approved','rejected','cancelled');

create table if not exists public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.departments (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  parent_department_id uuid references public.departments(id) on delete set null,
  name text not null,
  slug text not null,
  description text,
  department_type text not null default 'general',
  is_enabled boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, slug)
);
create index if not exists departments_org_parent_idx on public.departments(organization_id, parent_department_id, sort_order);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  email text,
  job_title text,
  department_id uuid references public.departments(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.organization_memberships (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  status public.membership_status not null default 'invited',
  is_organization_admin boolean not null default false,
  created_at timestamptz not null default now(),
  unique (organization_id, user_id)
);
create index if not exists organization_memberships_user_idx on public.organization_memberships(user_id, organization_id);

create table if not exists public.roles (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid references public.organizations(id) on delete cascade,
  name text not null,
  description text,
  is_system_role boolean not null default false,
  created_at timestamptz not null default now(),
  unique (organization_id, name)
);

create table if not exists public.permissions (
  id uuid primary key default gen_random_uuid(),
  permission_key text not null unique,
  description text not null
);

create table if not exists public.role_permissions (
  role_id uuid not null references public.roles(id) on delete cascade,
  permission_id uuid not null references public.permissions(id) on delete cascade,
  primary key (role_id, permission_id)
);

create table if not exists public.membership_roles (
  membership_id uuid not null references public.organization_memberships(id) on delete cascade,
  role_id uuid not null references public.roles(id) on delete cascade,
  primary key (membership_id, role_id)
);

create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  ticket_number bigint generated by default as identity,
  title text not null,
  description text not null default '',
  status public.ticket_status not null default 'new',
  priority public.ticket_priority not null default 'medium',
  requester_id uuid references auth.users(id) on delete set null,
  assignee_id uuid references auth.users(id) on delete set null,
  department_id uuid references public.departments(id) on delete set null,
  category text,
  source text not null default 'portal',
  due_at timestamptz,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, ticket_number)
);
create index if not exists tickets_org_status_idx on public.tickets(organization_id, status, priority, created_at desc);
create index if not exists tickets_assignee_idx on public.tickets(assignee_id, status);
create index if not exists tickets_requester_idx on public.tickets(requester_id, created_at desc);

