-- Membership-scoped read policies. Production writes should be mediated by
-- carefully scoped policies or server-side functions that validate permissions.
create policy "members can read own organizations" on public.organizations
for select using (public.is_org_member(id));

create policy "members can read departments" on public.departments
for select using (public.is_org_member(organization_id));

create policy "users can read own profile" on public.profiles
for select using (id = auth.uid());

create policy "members can read memberships in their organizations" on public.organization_memberships
for select using (user_id = auth.uid() or public.is_org_member(organization_id));

create policy "members can read organization roles" on public.roles
for select using (organization_id is null or public.is_org_member(organization_id));

create policy "authenticated users can read permission catalog" on public.permissions
for select to authenticated using (true);

create policy "members can read role permission mappings" on public.role_permissions
for select using (exists (
  select 1 from public.roles r
  where r.id = role_id and (r.organization_id is null or public.is_org_member(r.organization_id))
));

create policy "members can read membership role mappings" on public.membership_roles
for select using (exists (
  select 1 from public.organization_memberships m
  where m.id = membership_id and public.is_org_member(m.organization_id)
));

create policy "members can read tickets in their organizations" on public.tickets
for select using (public.is_org_member(organization_id));

create policy "members can read assets in their organizations" on public.assets
for select using (public.is_org_member(organization_id));

create policy "members can read published knowledge and own drafts" on public.knowledge_articles
for select using (
  public.is_org_member(organization_id)
  and (status = 'published' or created_by = auth.uid())
);

create policy "members can read audit events in their organizations" on public.audit_events
for select using (public.is_org_member(organization_id));

create policy "requesters and organization members can read AI approvals" on public.ai_action_approvals
for select using (requested_by = auth.uid() or public.is_org_member(organization_id));

